                <h2>В чем отличие между материалами для LCD или DLP принтеров и продуктами для настольных SLA?</h2>
                <p>
                    Многие ошибочно полагают, что разница заключается в длине волны, на которой работает принтер. Но это не так: настольные лазерные принтеры чаще всего используют ту же длину волны — 405 нм.
                </p>
                <p><b>Основное отличие — в скорости отверждения.</b></p>
                </p>
                <p>
                    На лазерных принтерах материал получает энергию от лазера в небольшой точке, тогда как на LCD-принтерах весь слой отверждается одновременно, но с меньшей интенсивностью.
                </p>
                <p>
                    Поэтому для лазерных принтеров материал должен быть менее чувствительным к ультрафиолету, чем материалы для масочной технологии печати. Это связано со скоростью движения лазера, если материал слишком чувствителен, он будет пересвечиваться. И наоборот, для LCD-принтеров интенсивности обычно недостаточно, чтобы качественно отвердить более медленные материалы для SLA.
                </p>
                <p>
                    Еще один важный момент в том, что большинство настольных лазерных принтеров являются закрытыми системами, где пользователь не может изменять режимы печати (не только экспозицию слоя, но и, например, скорость движения платформы или паузы).
                </p>
                <p>
                    Поэтому при разработке материала для SLA-принтеров необходимо учитывать все эти факторы и создавать продукт, который стабильно работает в фиксированных режимах принтера.
                </p>
