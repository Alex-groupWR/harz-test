            <h2>
            Отделение готового изделия  
            </h2>
            <p>
                Silicone Compatible Model V2 допускает использование разделителя для облегчения снятия затвердевшего силикона с модели. Мы убедились, что такие составы, как Mann Ease Release 200, а также восковая разделительная смазка Вс-М не препятствуют отверждению, по крайней мере с теми марками силикона, которые участвовали в испытаниях. 
            </p>
            <p>
            В то же время, в большинстве наших работ не использовался никакой разделительный состав. Проблема с разделением возникает из-за геометрии самой формы, поэтому при проектировании хорошей практикой будет сделать обратный конус на моделях, чтобы упростить снятие. Также имеет смысл добавить дополнительные воздушные каналы, чтобы можно было "выдуть" модель сжатым воздухом.  
            </p>
            <p>
                Наибольшая адгезия возникает на боковой поверхности, где проявляется шероховатость от слоёв и пиксельной сетки. Поэтому можно использовать сглаживание в настройках печати, чтобы получать более ровную поверхность. Также дополнительно стоит механически обрабатывать шероховатые поверхности.
            </p>
            <p>
                Аккуратно раскрыв форму, нужно тщательно срезать все литники и излишки силикона, которые могли образоваться при неполном смыкании частей формы.
