            <p>
                Во втором случае, использовать различные приспособления чтобы давить на силикон при заливке, например шприц. Здесь важно убедиться, что не осталось воздушных полостей и все пузыри вышли на поверхность через отведённые для них каналы и отверстия.
            </p>
            <p>
                Далее поместить форму в вакуумную камеру и закачать туда воздух с помощью подходящего компрессора. По нашему опыту, хороший результат заливки можно получить, если выдержать её под давлением 3-5 атм. в течение нескольких часов, либо оставить на ночь.
            </p>
