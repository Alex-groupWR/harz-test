            </h2>
            <p>
                После замешивания компонентов силикона в указанных производителем пропорциях, необходимо провести его дегазацию под вакуумом. Это позволит избавиться от воздушных пузырьков в готовом изделии.
            </p>
            <div class="center-position">
                <img class="img80" src="https://bx.harzlabs.ru/upload/medialibrary/027/jec8bha0oved6lx8bh00loqv643hzcz8/5_start.jpg" alt="заливка силикона в форму Silicone Compatible Model и дегазирование Silicone Compatible V2">
                <p align="center">Взвешивание силикона и последующая дегазация</p>
            </div>
            <br>
            <p>
                Для дегазации достаточно выдержать стакан с силиконом в вакуумной камере в течение 10-15 минут при минимально возможном давлении, которое позволяет достичь масляный вакуумный насос. В данном случае значение -1 атмосфера на манометре означает практически полную откачку воздуха из ёмкости. Важно не упустить начало отверждения и оставить достаточный запас времени, чтобы силикон ещё оставался жидким для успешной заливки.
            </p>
            <p>
                Необходимо убедиться, что при отборе нужного количества компонентов никакие посторонние предметы не попадают в ёмкости, в которых они хранятся, так как это может сделать силикон непригодным для дальнейшего использования.
            </p>
        </div>
