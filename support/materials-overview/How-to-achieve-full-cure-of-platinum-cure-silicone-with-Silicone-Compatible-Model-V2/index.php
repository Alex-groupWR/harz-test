            <h2>
            Заливка формы или мастер-модели силиконом 
            </h2>
            <p>
                В зависимости от способа проектирования, форма для заливки силикона может иметь широкое отверстие либо узкие каналы. В первом случае можно лить силикон сверху тонкой струёй, держа стакан на весу.
            </p>
            <div class="center-position">
                <img class="img80" src="https://bx.harzlabs.ru/upload/medialibrary/918/m2rzwbgwu9j772ewct8zmhwum9rg88p8/6_filling_form.jpg" alt="Заливка Silicone Compatible Model">
                <p align="center">Заливка силикона на весу</p>
            </div>
