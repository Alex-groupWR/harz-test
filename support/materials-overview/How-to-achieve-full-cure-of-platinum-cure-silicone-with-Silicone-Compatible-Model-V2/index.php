            <h2>
            Советы при проектировании моделей и форм 
            </h2>
            <p>
            <b>Не рекомендуется печатать пустотелые модели с заполнением</b> в виде различных структур и маленькими отверстиями для промывки, так как полностью вымыть жидкий полимер изнутри будет практически невозможно. Лучше всего проектировать модели с открытой гранью и стенкой 2-3 мм для упрощения процесса промывки и прогрева.   
            </p>
            <p>
            Если изготавливаются обратные формы, т.е. когда нужно изготовить деталь из силикона, а не мастер-модель для заливки, то лучше выполнять ее в формате "скорлупы" а не "кирпича-блока" по аналогии с пресс-формами для термопластавтомата, так как стенки меньшей толщины лучше прогреваются, что в свою очередь влияет на ингибирование силикона. 
            </p>
            <p>
            Добавки, такие как колеры и пигменты в том числе могут влиять на процесс ингибирования силикона, они замедляют реакцию и силикон может полностью не отверждаться при контакте с напечатанной моделью, тогда как натуральный силикон без добавок будет работать без каких-либо нареканий. Используйте красители и пигменты на свой страх и риск, предварительно проведя тесты на ингибирование на будущей модели.  
            </p>
