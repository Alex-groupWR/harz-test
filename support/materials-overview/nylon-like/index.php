                <h2>Работа с изделиями из фотополимера</h2>
                <p>
                    Материал является универсальным инженерным фотополимером, который позволяет изготавливать широкую номенклатуру изделий.  Механические свойства материала таковы, что позволяют упростить работу с изделиями при сборке и эксплуатации.
                </p>
                <ul class="und-list">
                    <li>Материал хорошо обрабатывается механически. При обработке фрезами не крошится и не дает сколов. Тонкие детали можно разрезать ножом или остро заточенной стамеской. Материал не будет ломаться, а будет образовывать ровную стружку.</li>
                    <li>При сборке частей корпусов можно использовать саморезы, закручивающиеся прямо в тело детали. Такой способ фиксации не является предпочтительным, но вполне может использоваться для быстрого прототипирования.</li>
                    <li>Для склейки деталей рекомендуется использовать составы с гибкой, эластичной основой. Например, полиуретановый клей, полиуретановый герметик и другие составы, которые могут деформироваться при нагрузках. Для быстрой сборки можно использовать цианоакрилатный клей, но гибкость соединения будет заметно хуже. Для получения хорошей адгезии клея к печатаемой детали необходимо обеспечить полное отверждение фотополимера. Если деталь плохо промыта, на поверхности остались подтеки жидкой смолы или материал был плохо засвечен, то адгезия будет низкой, соединение выйдет не прочным. </li>
                    <li>Для покраски аналогично рекомендуется использовать лакокрасочные материалы, обладающие повышенной гибкостью, например краски на полиуретановой основе. Изделия из этого фотополимера также можно покрывать акриловыми красками, но в случае деформации изделия под нагрузкой само покрытие может не выдержать и покрыться трещинами.</li>
                </ul>
