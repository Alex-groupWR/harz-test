                <h2>Рекомендации по печати</h2>
                <p>
                    Из-за сравнительно невысокой твердости материала при печати следует придерживаться следующих рекомендаций.
                </p>
                <p>
                    <b>1. Не располагайте плоские поверхности моделей параллельно платформе на поддержках.</b> Это может приводить к расслоению в нижней части модели. Рекомендуется наклонять такие поверхности на небольшой угол — около 2–3°. Если такой вариант расположения невозможен, используйте поддержки высокой плотности, например поддержки-блоки.
                </p>
